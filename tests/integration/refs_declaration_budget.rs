//! `refs` の出力予算と申告の代表パス (Issue #181)。
//!
//! 生成物 (`skipped.paths`) と解析できないソース (`truncations[].detail.examples`) の代表パスが
//! 長いと、申告だけで既定の予算 (3000) を使い切り、参照が 0 件まで削られていた。予算も超えた
//! ままで、`refs` の配列だけを見た利用者は「参照が無い」と読んでいた。代表パスは参照より先に
//! 縮め、件数は残し、縮めたことを `paths_limited_by` / `examples_limited_by` で申告する。

use super::support::*;
use astro_sight::output::estimated_tokens;

const NAMES: [&str; 4] = ["Alpha", "Beta", "Gamma", "Delta"];
const DEFAULT_BUDGET: usize = 3_000;
const GENERATED_DIR: &str = "generated/generator_output_directory_aaaa/nested_package_bbbbbbbb/another_level_cccccccc/and_one_more_level_dddddddddddddddd/yet_another_level_eeeeeeee";
const TEMPLATE_DIR: &str = "templates/very_long_template_directory_name_aaaaaaaa/nested_component_library_bbbbbbbbbbbb/another_deep_level_cccccccccc/views_dddddddddddddddd";
const UNANALYZABLE_EXTENSIONS: [&str; 10] = [
    "vue", "svelte", "astro", "mdx", "erb", "twig", "scala", "dart", "lua", "groovy",
];

/// 名前ごとに参照が 2 件 (定義 1 + 利用 1) ある PHP と、長いパスの生成物 `generated` 件。
/// `unanalyzable` なら、長いパスの解析できないソース (拡張子 10 種 × 3 件) も置く。
fn fixture(generated: usize, unanalyzable: bool) -> TestRepo {
    let repo = TestRepo::new();
    repo.create_dir_all("src");
    repo.write(
        "src/Models.php",
        "<?php\nclass Alpha {}\nclass Beta {}\nclass Gamma {}\nclass Delta {}\n",
    );
    repo.write(
        "src/Caller.php",
        "<?php\n$a = new Alpha();\n$b = new Beta();\n$c = new Gamma();\n$d = new Delta();\n",
    );
    repo.create_dir_all(GENERATED_DIR);
    for i in 1..=generated {
        repo.write(
            format!("{GENERATED_DIR}/generated_message_type_with_a_long_file_name_{i:02}.php"),
            format!(
                "<?php\n// Code generated by some-generator. DO NOT EDIT.\nclass GeneratedMessageTypeWithLongName{i:02} {{}}\n"
            ),
        );
    }
    if unanalyzable {
        repo.create_dir_all(TEMPLATE_DIR);
        for ext in UNANALYZABLE_EXTENSIONS {
            for i in 1..=3 {
                repo.write(
                    format!(
                        "{TEMPLATE_DIR}/component_template_with_a_rather_long_file_name_{i}.{ext}"
                    ),
                    "x\n",
                );
            }
        }
    }
    repo
}

/// `refs` の stdout (`global` は `--format` / `--pretty` などのグローバル引数)。
fn refs_stdout(repo: &TestRepo, global: &[&str], args: &[&str]) -> String {
    let output = cargo_bin()
        .args(global)
        .arg("refs")
        .args(args)
        .arg("--dir")
        .arg(repo.root())
        .output()
        .expect("run refs");
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).expect("UTF-8 stdout")
}

/// JSON (単一 / NDJSON) の結果。
fn json_records(text: &str) -> Vec<serde_json::Value> {
    if let Ok(value) = serde_json::from_str::<serde_json::Value>(text) {
        return vec![value];
    }
    text.lines()
        .filter(|line| !line.trim().is_empty())
        .map(|line| serde_json::from_str(line).expect("NDJSON record"))
        .collect()
}

/// 結果ごとの参照の件数。JSON (単一 / NDJSON / 配列) と TOON (`refs[N]` ヘッダ) を読む。
fn refs_per_result(text: &str) -> Vec<usize> {
    let as_json: Option<Vec<serde_json::Value>> = serde_json::from_str(text)
        .map(|value| vec![value])
        .ok()
        .or_else(|| {
            text.lines()
                .filter(|line| !line.trim().is_empty())
                .map(|line| serde_json::from_str(line).ok())
                .collect()
        });
    if let Some(records) = as_json {
        return records
            .iter()
            .flat_map(|record| match record.as_array() {
                Some(items) => items.clone(),
                None => vec![record.clone()],
            })
            .map(|record| record["refs"].as_array().map_or(0, Vec::len))
            .collect();
    }
    text.match_indices("refs[")
        .map(|(i, _)| {
            text[i + "refs[".len()..]
                .chars()
                .take_while(char::is_ascii_digit)
                .collect::<String>()
                .parse::<usize>()
                .expect("TOON の refs ヘッダには件数がある")
        })
        .collect()
}

fn single(name: &str) -> Vec<String> {
    vec!["--name".into(), name.into()]
}

fn batch() -> Vec<String> {
    vec!["--names".into(), NAMES.join(",")]
}

fn as_strs(args: &[String]) -> Vec<&str> {
    args.iter().map(String::as_str).collect()
}

/// 生成物のパスが長くても、既定の予算で全名前の参照が 2 件ずつ出て、出力も予算に収まる。
/// 代表パスは先頭からの prefix に縮み、全件数と `truncated` は残り、縮めたことを申告する。
#[test]
fn refs_keeps_references_when_generated_paths_exceed_the_budget() {
    let repo = fixture(60, false);

    // 対照: 予算を外せば代表パスは固定の上限 (50 件) まで出て、縮めた理由は付かない。
    let unlimited = json_records(&refs_stdout(
        &repo,
        &[],
        &["--name", "Alpha", "--token-budget", "unlimited"],
    ))
    .remove(0);
    let full_paths = unlimited["skipped"]["paths"].as_array().unwrap().clone();
    assert_eq!(full_paths.len(), 50, "{unlimited}");
    assert!(
        unlimited["skipped"].get("paths_limited_by").is_none(),
        "{unlimited}"
    );

    let text = refs_stdout(&repo, &[], &["--name", "Alpha"]);
    assert!(
        estimated_tokens(&text) <= DEFAULT_BUDGET,
        "{}",
        estimated_tokens(&text)
    );
    let json = json_records(&text).remove(0);
    assert_eq!(json["refs"].as_array().unwrap().len(), 2, "{json}");
    assert!(json.get("result_summary").is_none(), "{json}");
    let skipped = &json["skipped"];
    assert_eq!(skipped["generated"], 60);
    assert_eq!(skipped["truncated"], true);
    assert_eq!(skipped["paths_limited_by"], "token_budget");
    let paths = skipped["paths"].as_array().unwrap();
    assert!(!paths.is_empty() && paths.len() < 50, "{}", paths.len());
    assert_eq!(paths[..], full_paths[..paths.len()], "先頭からの prefix");

    // `--names` は呼び出し全体で 1 予算。申告は先頭の結果にだけ付く。
    let text = refs_stdout(&repo, &[], &as_strs(&batch()));
    assert!(
        estimated_tokens(&text) <= DEFAULT_BUDGET,
        "{}",
        estimated_tokens(&text)
    );
    let records = json_records(&text);
    assert_eq!(records.len(), 4);
    for (record, name) in records.iter().zip(NAMES) {
        assert_eq!(record["symbol"], name);
        assert_eq!(record["refs"].as_array().unwrap().len(), 2, "{record}");
        assert!(record.get("result_summary").is_none(), "{record}");
    }
    assert_eq!(records[0]["skipped"]["generated"], 60);
    assert_eq!(records[0]["skipped"]["paths_limited_by"], "token_budget");
    assert!(records[1..].iter().all(|r| r.get("skipped").is_none()));
}

/// 解析できないソースの代表パスが長くても参照は削らない。各申告の件数は残し、`message` は
/// 残した代表パスと一致させ、縮めた申告には理由を付ける。生成物との混在でも同じ。
#[test]
fn refs_keeps_references_when_unanalyzable_examples_exceed_the_budget() {
    for generated in [0, 60] {
        let repo = fixture(generated, true);
        for args in [single("Alpha"), batch()] {
            let text = refs_stdout(&repo, &[], &as_strs(&args));
            assert!(
                estimated_tokens(&text) <= DEFAULT_BUDGET,
                "{generated} {args:?}: {}",
                estimated_tokens(&text)
            );
            let records = json_records(&text);
            for record in &records {
                assert_eq!(record["refs"].as_array().unwrap().len(), 2, "{record}");
                assert!(record.get("result_summary").is_none(), "{record}");
            }
            let truncations = records[0]["truncations"].as_array().unwrap();
            assert_eq!(truncations.len(), 10, "{generated} {args:?}");
            for truncation in truncations {
                let detail = &truncation["detail"];
                assert_eq!(detail["count"], 3, "{truncation}");
                let examples: Vec<&str> = detail["examples"]
                    .as_array()
                    .unwrap()
                    .iter()
                    .map(|e| e.as_str().unwrap())
                    .collect();
                assert!(examples.len() < 3, "{truncation}");
                assert_eq!(detail["examples_limited_by"], "token_budget");
                let message = truncation["message"].as_str().unwrap();
                if examples.is_empty() {
                    assert!(!message.contains("(e.g."), "{message}");
                } else {
                    assert!(
                        message.ends_with(&format!("(e.g. {})", examples.join(", "))),
                        "{message}"
                    );
                }
            }
        }
    }
}

/// どの出力形式でも、最終的に返したテキストが予算に収まり、全名前の参照が出る。
#[test]
fn refs_keeps_references_in_every_output_format() {
    let repo = fixture(60, true);
    for global in [
        &[][..],
        &["--pretty"][..],
        &["--format", "toon"][..],
        &["--format", "auto"][..],
    ] {
        for (args, expected) in [(single("Alpha"), vec![2]), (batch(), vec![2; 4])] {
            let text = refs_stdout(&repo, global, &as_strs(&args));
            assert!(
                estimated_tokens(&text) <= DEFAULT_BUDGET,
                "{global:?} {args:?}: {}",
                estimated_tokens(&text)
            );
            assert_eq!(
                refs_per_result(&text),
                expected,
                "{global:?} {args:?}\n{text}"
            );
            assert!(!text.contains("budget_exceeded"), "{global:?} {args:?}");
        }
    }
}

/// 対照: 申告が予算に収まるなら、既定の予算でも出力は予算を外したときとバイト一致し、
/// 縮めた理由も付かない。
#[test]
fn refs_output_is_unchanged_when_declarations_fit_the_budget() {
    let repo = fixture(10, false);
    for args in [single("Alpha"), batch()] {
        let mut unlimited = args.clone();
        unlimited.extend(["--token-budget".into(), "unlimited".into()]);
        let limited = refs_stdout(&repo, &[], &as_strs(&args));
        assert_eq!(
            limited,
            refs_stdout(&repo, &[], &as_strs(&unlimited)),
            "{args:?}"
        );
        assert!(!limited.contains("limited_by"), "{limited}");
        assert_eq!(json_records(&limited)[0]["skipped"]["generated"], 10);
    }
}

/// MCP も tool result の text で採寸し、同じく参照を削らずに代表パスを縮める。
#[test]
fn mcp_refs_keeps_references_when_declaration_samples_exceed_the_budget() {
    let repo = fixture(60, true);
    let calls = [
        (
            "refs_search",
            serde_json::json!({ "name": "Alpha", "dir": "." }),
            vec![2],
        ),
        (
            "refs_batch_search",
            serde_json::json!({ "names": NAMES, "dir": "." }),
            vec![2; 4],
        ),
    ];
    for (tool, arguments, expected) in calls {
        for global in [&[][..], &["--format", "toon"][..]] {
            let request = serde_json::json!({
                "jsonrpc": "2.0",
                "id": 2,
                "method": "tools/call",
                "params": { "name": tool, "arguments": arguments }
            })
            .to_string();
            let stdout = mcp_send_after_init_with(global, Some(repo.root()), &[&request]);
            let line = stdout
                .lines()
                .find(|line| line.contains("\"id\":2"))
                .unwrap_or_else(|| panic!("{tool} のレスポンスが必要: {stdout}"));
            let response: serde_json::Value = serde_json::from_str(line).expect("JSON-RPC");
            let text = response["result"]["content"][0]["text"]
                .as_str()
                .unwrap_or_else(|| panic!("text が必要: {response}"));
            assert!(
                estimated_tokens(text) <= DEFAULT_BUDGET,
                "{tool} {global:?}: {}",
                estimated_tokens(text)
            );
            assert_eq!(refs_per_result(text), expected, "{tool} {global:?}\n{text}");
            assert!(
                text.contains("limited_by"),
                "{tool} {global:?}: 縮めたことを申告する"
            );
        }
    }
}

/// session も compact JSON の結果で採寸し、同じく参照を削らずに代表パスを縮める。
#[test]
fn session_refs_keeps_references_when_declaration_samples_exceed_the_budget() {
    use std::io::Write;
    use std::process::Stdio;

    let repo = fixture(60, true);
    let dir_json = serde_json::to_string(repo.root().to_str().expect("UTF-8 path")).unwrap();
    let names_json = serde_json::to_string(&NAMES).unwrap();
    let mut child = cargo_bin()
        .arg("session")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .expect("spawn session");
    {
        let stdin = child.stdin.as_mut().expect("stdin");
        writeln!(
            stdin,
            r#"{{"command":"refs","name":"Alpha","dir":{dir_json}}}"#
        )
        .unwrap();
        writeln!(
            stdin,
            r#"{{"command":"refs","names":{names_json},"dir":{dir_json}}}"#
        )
        .unwrap();
    }
    drop(child.stdin.take());
    let output = child.wait_with_output().expect("wait session");
    assert!(output.status.success());
    let stdout = String::from_utf8(output.stdout).expect("UTF-8 stdout");
    let lines: Vec<&str> = stdout.lines().collect();
    assert_eq!(lines.len(), 2, "{stdout}");
    for (line, expected) in lines.iter().zip([vec![2], vec![2; 4]]) {
        assert!(
            estimated_tokens(line) <= DEFAULT_BUDGET,
            "{}",
            estimated_tokens(line)
        );
        assert_eq!(refs_per_result(line), expected, "{line}");
        assert!(line.contains("limited_by"), "{line}");
    }
}
