//! `.gitattributes` の `linguist-generated` を、生成物を外すすべての経路が Git と同じ規則
//! (入れ子の `.gitattributes`・後勝ち・`!` で未指定に戻す) と同じ優先順位 (属性 → 名前 →
//! ヘッダー。unset と `false` はヘッダーを打ち消す) で扱うことの統合テスト (Issue #254)。

use super::support::*;

const HEADER: &str = "// Code generated by a tool. DO NOT EDIT.\n";

/// 属性だけの生成物・unset で残すヘッダー付きのファイル・`!` でヘッダーの判定に戻すファイル・
/// Linguist の値・入れ子の `.gitattributes` を持つリポジトリ。
fn attributes_repo() -> TestRepo {
    let repo = TestRepo::new();
    repo.init_git();
    for dir in ["gen", "src", "data", "pkg"] {
        repo.create_dir_all(dir);
    }
    repo.write(
        ".gitattributes",
        "gen/** linguist-generated\n\
         src/kept.ts -linguist-generated\n\
         src/back.ts linguist-generated\n\
         src/back.ts !linguist-generated\n\
         data/false.ts linguist-generated=false\n\
         data/zero.ts linguist-generated=0\n",
    );
    repo.write("pkg/.gitattributes", "*.out.ts linguist-generated\n");
    repo.write(
        "gen/client.ts",
        "export function generatedClient(): number {\n  return 1;\n}\n\nexport function unusedGenerated(): number {\n  return 0;\n}\n",
    );
    repo.write(
        "src/kept.ts",
        format!(
            "{HEADER}export function keptHelper(): number {{\n  return 2;\n}}\n\nexport function keptUnused(): number {{\n  return 0;\n}}\n"
        ),
    );
    repo.write(
        "src/back.ts",
        format!("{HEADER}export function backHelper(): number {{\n  return 3;\n}}\n"),
    );
    repo.write(
        "data/false.ts",
        format!("{HEADER}export function falseHelper(): number {{\n  return 4;\n}}\n"),
    );
    repo.write(
        "data/zero.ts",
        "export function zeroHelper(): number {\n  return 5;\n}\n",
    );
    repo.write(
        "pkg/x.out.ts",
        "export function outHelper(): number {\n  return 6;\n}\n\nexport function outUnused(): number {\n  return 0;\n}\n",
    );
    repo.write(
        "src/app.ts",
        "import { generatedClient } from \"../gen/client\";\n\
         import { keptHelper } from \"./kept\";\n\
         import { backHelper } from \"./back\";\n\
         import { falseHelper } from \"../data/false\";\n\
         import { zeroHelper } from \"../data/zero\";\n\
         import { outHelper } from \"../pkg/x.out\";\n\
         console.log(generatedClient() + keptHelper() + backHelper() + falseHelper() + zeroHelper() + outHelper());\n",
    );
    repo
}

/// 生成物として外すファイル (属性 set・`!` で戻したヘッダー・値 `0`・入れ子の属性)。
const GENERATED: [&str; 4] = [
    "data/zero.ts",
    "gen/client.ts",
    "pkg/x.out.ts",
    "src/back.ts",
];

fn sorted_strings(value: &serde_json::Value) -> Vec<String> {
    let mut items: Vec<String> = value
        .as_array()
        .unwrap_or_else(|| panic!("not an array: {value}"))
        .iter()
        .map(|item| item.as_str().unwrap().to_string())
        .collect();
    items.sort();
    items
}

fn ref_paths(output: &serde_json::Value) -> Vec<String> {
    let mut paths: Vec<String> = output["refs"]
        .as_array()
        .unwrap()
        .iter()
        .map(|r| r["path"].as_str().unwrap().to_string())
        .collect();
    paths.sort();
    paths.dedup();
    paths
}

/// refs は属性だけの生成物 (ヘッダーなし) を外して申告し、unset と `false` のヘッダー付きの
/// ファイルは検索する。修正前は属性を見ず、ヘッダーだけで判定していた。
/// 対照: `--include-generated` ではすべて検索する。
#[test]
fn refs_follow_linguist_generated_attributes() {
    let repo = attributes_repo();
    // 一括検索は名前ごとに 1 行を出し、走査の申告は先頭の行に付く。
    let output = cargo_bin()
        .args(["refs", "--dir"])
        .arg(repo.root())
        .args([
            "--names",
            "generatedClient,keptHelper,backHelper,falseHelper,zeroHelper,outHelper",
        ])
        .output()
        .expect("run refs --names");
    assert!(output.status.success());
    let stdout = String::from_utf8(output.stdout).unwrap();
    let first: serde_json::Value = serde_json::from_str(stdout.lines().next().unwrap()).unwrap();
    assert_eq!(
        sorted_strings(&first["skipped"]["paths"]),
        GENERATED,
        "{stdout}"
    );
    let single = repo.run_json("refs", &["--name", "keptHelper"]);
    assert_eq!(
        ref_paths(&single),
        ["src/app.ts", "src/kept.ts"],
        "unset はヘッダーを打ち消す: {single}"
    );
    let single = repo.run_json("refs", &["--name", "falseHelper"]);
    assert_eq!(
        ref_paths(&single),
        ["data/false.ts", "src/app.ts"],
        "値 false はヘッダーを打ち消す: {single}"
    );
    let single = repo.run_json("refs", &["--name", "outHelper"]);
    assert_eq!(ref_paths(&single), ["src/app.ts"], "入れ子の属性: {single}");
    assert_eq!(
        sorted_strings(&single["skipped"]["paths"]),
        GENERATED,
        "{single}"
    );

    let all = repo.run_json("refs", &["--name", "outHelper", "--include-generated"]);
    assert_eq!(ref_paths(&all), ["pkg/x.out.ts", "src/app.ts"], "{all}");
    assert!(all.get("skipped").is_none(), "{all}");
}

/// symbols --dir も同じファイルを外し、末尾の行で申告する。
#[test]
fn symbols_dir_follows_linguist_generated_attributes() {
    let repo = attributes_repo();
    let output = cargo_bin()
        .args(["symbols", "--dir"])
        .arg(repo.root())
        .output()
        .expect("run symbols --dir");
    assert!(output.status.success());
    let records: Vec<serde_json::Value> = String::from_utf8(output.stdout)
        .unwrap()
        .lines()
        .map(|line| serde_json::from_str(line).unwrap())
        .collect();
    let mut paths: Vec<&str> = records.iter().filter_map(|r| r["path"].as_str()).collect();
    paths.sort();
    assert_eq!(
        paths,
        ["data/false.ts", "src/app.ts", "src/kept.ts"],
        "{records:?}"
    );
    let trailer = records.last().unwrap();
    assert_eq!(
        sorted_strings(&trailer["skipped"]["paths"]),
        GENERATED,
        "{trailer}"
    );
}

/// dead-code は属性で生成物のファイルを候補から外し (入れ子の属性も読む)、unset で残した
/// ヘッダー付きのファイルの未使用の export を dead と報告する。修正前は入れ子の属性を読まず
/// (`outUnused` を dead と報告)、unset でもヘッダーで外していた (`keptUnused` を見落とす)。
#[test]
fn dead_code_follows_linguist_generated_attributes() {
    let repo = attributes_repo();
    let output = repo.run_json("dead-code", &[]);
    let mut dead: Vec<&str> = output["dead_symbols"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(|symbol| symbol["name"].as_str())
        .collect();
    dead.sort();
    assert_eq!(dead, ["keptUnused"], "{output}");
    assert_eq!(
        sorted_strings(&output["generated_candidates_skipped"]["paths"]),
        GENERATED,
        "{output}"
    );
}

/// review の API 差分は、入れ子の属性で生成物のファイルの変更を外し、unset で残した
/// ヘッダー付きのファイルの変更を数える。
#[test]
fn api_diff_follows_linguist_generated_attributes() {
    let repo = attributes_repo();
    repo.commit_all("initial");
    repo.write(
        "src/kept.ts",
        format!("{HEADER}export function keptHelper(): number {{\n  return 2;\n}}\n"),
    );
    repo.write(
        "pkg/x.out.ts",
        "export function outHelper(): number {\n  return 6;\n}\n",
    );
    let output = repo.run_json("review", &["--git"]);
    let removed: Vec<(String, String)> = ["removed", "removed_dead"]
        .iter()
        .filter_map(|bucket| output["api_changes"].get(*bucket)?.as_array().cloned())
        .flatten()
        .filter_map(|symbol| {
            Some((
                symbol["name"].as_str()?.to_string(),
                symbol["file"].as_str()?.to_string(),
            ))
        })
        .collect();
    assert_eq!(
        removed,
        [("keptUnused".to_string(), "src/kept.ts".to_string())],
        "{output}"
    );
}

/// session は要求ごとに属性を解決し直すので、`.gitattributes` を変えると次の要求に反映する。
#[test]
fn session_reflects_attribute_changes_between_requests() {
    use std::io::{BufRead, Write};
    use std::process::Stdio;

    let repo = attributes_repo();
    let mut child = cargo_bin()
        .arg("session")
        .env("ASTRO_SIGHT_WORKSPACE", repo.root())
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .expect("failed to spawn session");
    let mut stdin = child.stdin.take().unwrap();
    let mut stdout = std::io::BufReader::new(child.stdout.take().unwrap());
    let mut request = |stdin: &mut std::process::ChildStdin| {
        writeln!(
            stdin,
            r#"{{"command":"refs","name":"generatedClient","dir":"."}}"#
        )
        .unwrap();
        stdin.flush().unwrap();
        let mut line = String::new();
        stdout.read_line(&mut line).unwrap();
        serde_json::from_str::<serde_json::Value>(&line).unwrap()
    };

    let before = request(&mut stdin);
    assert_eq!(ref_paths(&before), ["src/app.ts"], "{before}");
    repo.write(".gitattributes", "src/back.ts linguist-generated\n");
    let after = request(&mut stdin);
    assert_eq!(
        ref_paths(&after),
        ["gen/client.ts", "src/app.ts"],
        "属性を外したので次の要求では検索する: {after}"
    );
    drop(stdin);
    assert!(child.wait().unwrap().success());
}

/// 属性を解決できない (index が壊れている) ときは、ヘッダーがあっても生成物として外さず、
/// `generated_detection_unavailable` で申告する (unset で残すと宣言しているかを確かめられない)。
/// 対照: index を直せばヘッダーで外す。
#[test]
fn attribute_lookup_failure_keeps_files_and_reports_it() {
    let repo = TestRepo::new();
    repo.init_git();
    repo.create_dir_all("src");
    repo.write(
        "src/gen.ts",
        format!("{HEADER}export function markedHelper(): number {{\n  return 1;\n}}\n"),
    );
    repo.write(
        "src/app.ts",
        "import { markedHelper } from \"./gen\";\nmarkedHelper();\n",
    );
    repo.stage_all();
    let index = repo.path(".git/index");
    let original = std::fs::read(&index).unwrap();
    std::fs::write(&index, b"not an index").unwrap();

    let output = repo.run_json("refs", &["--name", "markedHelper"]);
    assert_eq!(ref_paths(&output), ["src/app.ts", "src/gen.ts"], "{output}");
    assert!(output.get("skipped").is_none(), "{output}");
    let truncations = output["truncations"].as_array().unwrap();
    assert_eq!(truncations.len(), 1, "{output}");
    assert_eq!(truncations[0]["reason"], "generated_detection_unavailable");
    let message = truncations[0]["message"].as_str().unwrap();
    assert!(message.contains("2 file(s)"), "{message}");
    assert!(
        !message.contains(repo.root().to_string_lossy().as_ref()),
        "絶対パスを含めない: {message}"
    );

    std::fs::write(&index, original).unwrap();
    let output = repo.run_json("refs", &["--name", "markedHelper"]);
    assert_eq!(ref_paths(&output), ["src/app.ts"], "{output}");
    assert!(output.get("truncations").is_none(), "{output}");
}
